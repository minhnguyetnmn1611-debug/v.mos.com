(function () {
  try { window.currentLang = localStorage.getItem('lang') || 'vi'; } catch (e) { window.currentLang = 'vi'; }

  window.t = function (key, fallback) {
    const dict = I18N_TRANSLATIONS[window.currentLang] || I18N_TRANSLATIONS['vi'];
    if (dict && dict[key] !== undefined) {
      return dict[key];
    }
    // Fallback to Vietnamese if missing in requested lang
    const defaultDict = I18N_TRANSLATIONS['vi'];
    if (defaultDict && defaultDict[key] !== undefined) {
      return defaultDict[key];
    }
    return fallback || key;
  };

  window.setLanguage = function (lang) {
    if (!I18N_TRANSLATIONS[lang]) lang = 'vi';
    window.currentLang = lang;
    try { localStorage.setItem('lang', lang); } catch (e) { /* trình duyệt chặn lưu trữ */ }
    document.documentElement.setAttribute('lang', lang);

    // Update innerText / textContent
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = window.t(key);
      if (text) el.textContent = text;
    });

    // Update input placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const text = window.t(key);
      if (text) el.placeholder = text;
    });

    // Update attributes like "attrName:key"
    document.querySelectorAll('[data-i18n-attr]').forEach(el => {
      const val = el.getAttribute('data-i18n-attr');
      if (val && val.includes(':')) {
        const [attr, key] = val.split(':');
        const text = window.t(key);
        if (text) el.setAttribute(attr, text);
      }
    });

    // Update active UI elements
    document.querySelectorAll('.lang-select-btn').forEach(btn => {
      btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });

    document.querySelectorAll('.lang-current-label').forEach(label => {
      label.textContent = lang.toUpperCase();
    });
  };

  // Run initial language apply as early as possible
  window.setLanguage(window.currentLang);

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', function () {
      window.setLanguage(window.currentLang);
    });
  }
})();